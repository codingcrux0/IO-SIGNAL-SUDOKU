"""Governed rule changes: engineers add project rules from dropdowns, then someone verifies them.

How it works:
  1. An engineer picks a rule TYPE from a fixed list of templates and fills in its fields
     (dropdowns or short text).  The rule's wording is generated by CODE from the template -
     never typed free-hand - so a rule is always one of the known kinds with valid values.
  2. The proposal waits as 'pending'.  It changes nothing.
  3. Someone reviews it in the Review Queue and presses Verify (verify()) or Reject (dismiss()).  This
     prototype has no passcode and no login: verifying is one button.  Only a verified (approved)
     proposal can be used by apply_approved() to build a NEW rule-pack version.
  4. Every step is recorded in an audit log.
approve()/reject() are the stricter gate (a different person and an approver passcode); they are
kept for a deployment that wants it.
The LOCKED rules (capacity, CHARM formula, alarm baseplate, A/B separation ...) have no template,
so they cannot be proposed at all.
"""
from __future__ import annotations

import hashlib
import hmac
import json
from dataclasses import dataclass
from typing import Any

from io_sudoku.core.config import Config, load_config
from io_sudoku.core.constants import IO_TYPES, PROFILES
from io_sudoku.core.projectrules import CHECK_COLUMNS, MATCH_COLUMNS, charm_types
from io_sudoku.core.rulepack import RulePack, apply_pack, derive, validate_pack
from io_sudoku.core.textnorm import clean, match_key


@dataclass(frozen=True)
class ArgSpec:
    name: str
    kind: str                       # 'choice' | 'int' | 'text'
    choices: tuple[str, ...] = ()
    lo: int | None = None
    hi: int | None = None
    max_len: int = 40


@dataclass(frozen=True)
class RuleTemplate:
    key: str
    label: str
    args: tuple[ArgSpec, ...]
    statement: str                  # {placeholders} are filled with the validated arguments


_PROFILE_CHOICES = tuple(p for p in PROFILES if p != "AIR_RTD")
TEMPLATES: dict[str, RuleTemplate] = {t.key: t for t in (
    RuleTemplate("io_alias", "New IO type name", (ArgSpec("alias", "text", max_len=20), ArgSpec("io", "choice", IO_TYPES)),
                 "Treat IO type '{alias}' as {io}."),
    RuleTemplate("high_current_keyword", "High-current keyword", (ArgSpec("keyword", "text"),),
                 "Treat '{keyword}' loads as high-current DOR (SE4302T02 / SE4502)."),
    RuleTemplate("instrument_profile", "Instrument hardware", (ArgSpec("instrument", "text", max_len=60), ArgSpec("profile", "choice", _PROFILE_CHOICES)),
                 "Use hardware profile {profile} for instrument type '{instrument}'."),
    RuleTemplate("segregation_family", "Segregation code", (ArgSpec("code", "text", max_len=20), ArgSpec("family", "choice", ("A", "B", "neutral"))),
                 "Treat segregation code '{code}' as family {family}."),
    RuleTemplate("spare_pct", "Wired-spare percentage", (ArgSpec("value", "int", lo=0, hi=30),),
                 "Allocate {value}% wired spares per IO type per controller."),
    RuleTemplate("future_pct", "Future-space percentage", (ArgSpec("value", "int", lo=0, hi=30),),
                 "Keep {value}% of each cabinet as future Spare Slots."),
    RuleTemplate("end_reserve_bps", "Empty end baseplates", (ArgSpec("value", "int", lo=0, hi=8),),
                 "Keep the last {value} baseplates of CIOC 4 empty."),
    RuleTemplate("add_cabinet", "Add a cabinet", (ArgSpec("room", "choice"),),
                 "Add one more marshalling cabinet in {room}."),
    # project columns and constraints on CHARM signals (see projectrules: they never move a signal)
    RuleTemplate("project_column", "New project column",
                 (ArgSpec("column", "text", max_len=30), ArgSpec("value", "text", max_len=40),
                  ArgSpec("match_column", "choice", MATCH_COLUMNS), ArgSpec("match_text", "text", max_len=40)),
                 "Add the project column '{column}' = '{value}' to every signal whose {match_column} contains '{match_text}'."),
    RuleTemplate("expect_hardware", "Hardware constraint",
                 (ArgSpec("match_column", "choice", MATCH_COLUMNS), ArgSpec("match_text", "text", max_len=40),
                  ArgSpec("charm_type", "choice", charm_types())),
                 "Every signal whose {match_column} contains '{match_text}' must use CHARM {charm_type}."),
    RuleTemplate("require_filled", "Required-value constraint",
                 (ArgSpec("match_column", "choice", MATCH_COLUMNS), ArgSpec("match_text", "text", max_len=40),
                  ArgSpec("check_column", "choice", CHECK_COLUMNS)),
                 "Every signal whose {match_column} contains '{match_text}' must have {check_column} filled in."),
)}
PROJECT_TEMPLATES = ("project_column", "expect_hardware", "require_filled")


@dataclass
class RuleProposal:
    id: str
    template: str
    args: dict[str, Any]
    statement: str
    source: str                     # 'form' or 'ai'
    status: str                     # 'pending' | 'approved' | 'rejected'
    author: str
    reviewer: str | None = None
    created: str = ""
    decided: str | None = None
    reason: str | None = None
    rationale: str | None = None    # the AI's explanation (information only, never the rule itself)


def template_catalogue(known_rooms: list[str]) -> list[dict[str, Any]]:
    """What the dropdown form needs: every template with its fields and allowed values."""
    out = []
    for t in TEMPLATES.values():
        args = [{"name": a.name, "kind": a.kind, "choices": list(known_rooms if (t.key == "add_cabinet" and a.name == "room") else a.choices),
                 "lo": a.lo, "hi": a.hi, "max_len": a.max_len} for a in t.args]
        out.append({"key": t.key, "label": t.label, "statement": t.statement, "args": args})
    return out


def _validate_args(template: RuleTemplate, args: dict[str, Any], known_rooms: list[str]) -> tuple[dict[str, Any], list[str]]:
    errors: list[str] = []
    clean_args: dict[str, Any] = {}
    names = {a.name for a in template.args}
    for extra in sorted(set(args) - names):
        errors.append(f"'{extra}' is not a field of this rule.")
    for spec in template.args:
        if spec.name not in args:
            errors.append(f"Please fill in '{spec.name}'.")
            continue
        value = args[spec.name]
        if spec.kind == "int":
            ok = isinstance(value, int) and not isinstance(value, bool) or (isinstance(value, str) and value.strip().isdigit())
            number = int(value) if ok else None
            if number is None or not (spec.lo is not None and spec.hi is not None and spec.lo <= number <= spec.hi):
                errors.append(f"'{spec.name}' must be a whole number from {spec.lo} to {spec.hi}.")
            else:
                clean_args[spec.name] = number
        elif spec.kind == "choice":
            choices = known_rooms if (template.key == "add_cabinet" and spec.name == "room") else list(spec.choices)
            match = next((c for c in choices if match_key(c) == match_key(value)), None)
            if match is None:
                errors.append(f"'{value}' is not one of the allowed values for '{spec.name}'.")
            else:
                clean_args[spec.name] = match
        else:
            text = clean(value)
            if text is None or len(text) > spec.max_len or any(ord(ch) < 32 for ch in text):
                errors.append(f"'{spec.name}' must be 1 to {spec.max_len} plain characters.")
            else:
                clean_args[spec.name] = text
    return clean_args, errors


def build_proposal(template: str, args: dict[str, Any], author: str, source: str = "form", rationale: str | None = None,
                   now: str = "", known_rooms: list[str] | None = None) -> tuple[RuleProposal | None, list[str]]:
    """Validate and create a PENDING proposal, or return (None, reasons it was refused)."""
    spec = TEMPLATES.get(template)
    if spec is None:
        return None, [f"'{template}' is not a supported kind of rule."]
    if not clean(author):
        return None, ["Please enter your name as the author."]
    rooms = known_rooms if known_rooms is not None else load_config().known_rooms()
    clean_args, errors = _validate_args(spec, dict(args), rooms)
    if errors:
        return None, errors
    statement = spec.statement.format(**clean_args)
    digest = hashlib.sha256((template + json.dumps(clean_args, sort_keys=True) + str(author) + now).encode("utf-8")).hexdigest()[:8]
    return RuleProposal(f"RC-{digest}", template, clean_args, statement, "ai" if source == "ai" else "form", "pending",
                        str(author).strip(), None, now, None, None, rationale), []


def is_approver(passcode: str | None, secret: str | None) -> bool:
    """True only if a secret is configured AND the passcode equals it (constant-time comparison)."""
    if not passcode or not secret:
        return False
    return hmac.compare_digest(str(passcode).encode("utf-8"), str(secret).encode("utf-8"))


def _decision_errors(p: RuleProposal, reviewer: str, passcode: str | None, secret: str | None) -> list[str]:
    errors: list[str] = []
    if not secret:
        errors.append("Approvals are switched off: no approver passcode has been configured.")
    elif not is_approver(passcode, secret):
        errors.append("The approver passcode is missing or wrong.")
    if not clean(reviewer):
        errors.append("Please enter your name as the reviewer.")
    elif match_key(reviewer) == match_key(p.author):
        errors.append("You cannot decide on your own proposal: a different person must review it.")
    if p.status != "pending":
        errors.append("This proposal has already been decided.")
    return errors


def approve(p: RuleProposal, reviewer: str, passcode: str | None, secret: str | None, now: str) -> list[str]:
    """Approve a pending proposal. Returns [] on success, otherwise the reasons it was refused."""
    errors = _decision_errors(p, reviewer, passcode, secret)
    if errors:
        return errors
    p.status, p.reviewer, p.decided = "approved", str(reviewer).strip(), now
    return []


def reject(p: RuleProposal, reviewer: str, reason: str, passcode: str | None, secret: str | None, now: str) -> list[str]:
    errors = _decision_errors(p, reviewer, passcode, secret)
    if not clean(reason):
        errors.append("Please give a reason for rejecting.")
    if errors:
        return errors
    p.status, p.reviewer, p.decided, p.reason = "rejected", str(reviewer).strip(), now, str(reason).strip()
    return []


PROTOTYPE_REVIEWER = "Reviewer"


def verify(p: RuleProposal, now: str, reviewer: str = "") -> list[str]:
    """Prototype approval: one Verify button, no passcode.  Returns [] on success."""
    if p.status != "pending":
        return ["This proposal has already been decided."]
    p.status, p.reviewer, p.decided = "approved", clean(reviewer) or PROTOTYPE_REVIEWER, now
    return []


def dismiss(p: RuleProposal, now: str, reason: str = "", reviewer: str = "") -> list[str]:
    """Prototype rejection: no passcode; the reason is optional."""
    if p.status != "pending":
        return ["This proposal has already been decided."]
    p.status, p.reviewer, p.decided = "rejected", clean(reviewer) or PROTOTYPE_REVIEWER, now
    p.reason = clean(reason) or "Rejected in the Review Queue."
    return []


def apply_approved(pack: RulePack, proposals: list[RuleProposal], cfg: Config | None = None) -> RulePack:
    """A NEW pack version holding every APPROVED proposal; pending and rejected ones are ignored.

    Returns the original pack unchanged if nothing is approved or the result would be invalid."""
    approved = sorted((p for p in proposals if p.status == "approved"), key=lambda p: (p.created, p.id))
    if not approved:
        return pack
    new = derive(pack)
    params, overrides = dict(new.params), {k: (dict(v) if isinstance(v, dict) else list(v)) for k, v in new.overrides.items()}
    for p in approved:
        a = p.args
        if p.template == "io_alias":
            overrides.setdefault("io_aliases", {})[str(a["alias"]).upper()] = a["io"]
        elif p.template == "high_current_keyword":
            words = overrides.setdefault("high_current_keywords", [])
            if str(a["keyword"]).lower() not in words:
                words.append(str(a["keyword"]).lower())
        elif p.template == "instrument_profile":
            overrides.setdefault("instrument_profiles", {})[a["instrument"]] = a["profile"]
        elif p.template == "segregation_family":
            overrides.setdefault("segregation_families", {})[str(a["code"]).upper()] = a["family"]
        elif p.template in ("spare_pct", "future_pct", "end_reserve_bps"):
            params[p.template] = int(a["value"])
        elif p.template in PROJECT_TEMPLATES:
            overrides.setdefault("project_rules", []).append(
                {"id": p.id, "kind": p.template, "args": dict(a), "statement": p.statement})
        elif p.template == "add_cabinet":
            so_far = RulePack(new.name, new.version, new.parent, params, overrides, False)
            cab = apply_pack(so_far, cfg or load_config()).new_cabinet_for_room(a["room"])
            if cab is not None:
                overrides.setdefault("extra_cabinets", []).append({k: getattr(cab, k) for k in (
                    "marshalling", "system", "controller", "tech_room", "loc", "area5", "unit", "cabinet_seq", "ctrl_seq")})
    result = RulePack(new.name, new.version, new.parent, params, overrides, False)
    return pack if validate_pack(result) else result


def row_diff_summary(rows_before: list[dict[str, Any]], rows_after: list[dict[str, Any]]) -> dict[str, int]:
    """How many cells changed per column between two result sets (matched by slot). {} = identical."""
    def key(r: dict[str, Any]) -> tuple:
        return (str(r.get("Electronic/ Marshalling Cabinet")), str(r.get("CIOC/CSLS Name")), str(r.get("Baseplate")), str(r.get("Channel_No")))
    before, after = {key(r): r for r in rows_before}, {key(r): r for r in rows_after}
    changed: dict[str, int] = {}
    for k in before.keys() & after.keys():
        for column in before[k]:
            if before[k].get(column) != after[k].get(column):
                changed[column] = changed.get(column, 0) + 1
    gone, new = len(before.keys() - after.keys()), len(after.keys() - before.keys())
    if gone or new:
        changed["(slots only in one result)"] = gone + new
    return dict(sorted(changed.items()))


def audit_entries(proposals: list[RuleProposal]) -> list[dict[str, Any]]:
    """Every state change of every proposal, oldest first."""
    entries: list[dict[str, Any]] = []
    for p in proposals:
        entries.append({"when": p.created, "proposal": p.id, "event": "proposed", "by": p.author, "source": p.source,
                        "statement": p.statement, "detail": p.rationale or ""})
        if p.status in ("approved", "rejected"):
            entries.append({"when": p.decided or "", "proposal": p.id, "event": p.status, "by": p.reviewer or "", "source": p.source,
                            "statement": p.statement, "detail": p.reason or ""})
    return sorted(entries, key=lambda e: (e["when"], e["proposal"], e["event"]))
